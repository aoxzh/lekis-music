typedef PageFetcher<T> = Future<List<T>> Function(int offset, int limit);
typedef ListCount = Future<int> Function();

/// A sparse, page-cached view over a very long list (100k+ rows).
///
/// * Pages are fetched on demand when [itemAt] hits an unloaded page.
/// * Only [maxCachedPages] pages are kept (LRU), so memory stays flat.
/// * The total count comes from an exact `count*` bridge call when available;
///   otherwise it is discovered lazily (see [_probeTotal]).
class PagedList<T> extends ChangeNotifier {
  PagedList({
    required this._fetch,
    this.pageSize = 200,
    this.maxCachedPages = 40,
    this.count,
  }) {
    _load(0);
  }

  final PageFetcher<T> _fetch;

  /// Exact total row count, when the bridge can provide one.
  final ListCount? count;
  final int pageSize;
  final int maxCachedPages;

  // ignore: prefer_collection_literals — LinkedHashMap keeps LRU order.
  final LinkedHashMap<int, List<T>> _pages = LinkedHashMap<int, List<T>>();
  final Set<int> _inFlight = <int>{};
  int? _total;
  int _knownEnd = 0;
  bool _firstPageLoaded = false;
  bool _probing = false;
  bool _disposed = false;
  Object? _error;

  Object? get error => _error;
  bool get isInitialLoading => !_firstPageLoaded && _error == null;
  bool get isEmpty => _total == 0;

  /// Exact once known; until then a speculative count that grows by one page
  /// beyond what we know exists, so scrolling keeps pulling pages in.
  int get itemCount => _total ?? (_knownEnd + pageSize);

  /// Returns the item, or `null` while its page is loading.
  T? itemAt(int index) {
    if (index < 0) return null;
    final total = _total;
    if (total != null && index >= total) return null;
    final page = index ~/ pageSize;
    final rows = _pages.remove(page);
    if (rows == null) {
      _load(page);
      return null;
    }
    _pages[page] = rows; // touch (LRU)
    final i = index - page * pageSize;
    return i < rows.length ? rows[i] : null;
  }

  /// Loaded, contiguous items around [index] (for building a play queue
  /// without sending 100k ids). Returns the ids window and the start offset.
  (List<T> items, int start) loadedWindow(int index) {
    final page = index ~/ pageSize;
    final out = <T>[];
    var start = 0;
    for (var p = page - 1; p <= page + 1; p++) {
      final rows = _pages[p];
      if (rows == null) {
        if (p < page) continue;
        break;
      }
      if (p == page) start = out.length + (index - page * pageSize);
      out.addAll(rows);
    }
    return (out, start);
  }

  void retry() {
    _error = null;
    notifyListeners();
    _load(0);
  }

  void _load(int page) {
    if (_disposed || _inFlight.contains(page)) return;
    _inFlight.add(page);
    _fetch(page * pageSize, pageSize).then(
      (rows) {
        _inFlight.remove(page);
        if (_disposed) return;
        _pages[page] = rows;
        if (page == 0) _firstPageLoaded = true;
        if (rows.length < pageSize) {
          _total = page * pageSize + rows.length;
        } else {
          _knownEnd = math.max(_knownEnd, (page + 1) * pageSize);
          if (page == 0) unawaited(_probeTotal());
        }
        while (_pages.length > maxCachedPages) {
          _pages.remove(_pages.keys.first);
        }
        notifyListeners();
      },
      onError: (Object e) {
        _inFlight.remove(page);
        if (_disposed) return;
        if (page == 0) _error = e;
        notifyListeners();
      },
    );
  }

  /// Gets the exact row count so the scrollbar is accurate and the user can
  /// fling straight to the end. Prefers the bridge's `count*` call; the
  /// single-row binary search is only a fallback for lists without one.
  Future<void> _probeTotal() async {
    if (_probing) return;
    _probing = true;
    try {
      if (count != null) {
        final total = await count!();
        if (_disposed || _total != null) return;
        _total = total;
        notifyListeners();
        return;
      }
      Future<bool> exists(int i) async => (await _fetch(i, 1)).isNotEmpty;
      var lo = pageSize; // count >= lo
      var hi = pageSize * 2;
      while (await exists(hi - 1)) {
        if (_disposed || _total != null) return;
        lo = hi;
        hi *= 2;
      }
      while (hi - lo > 1) {
        if (_disposed || _total != null) return;
        final mid = (lo + hi) ~/ 2;
        if (await exists(mid - 1)) {
          lo = mid;
        } else {
          hi = mid;
        }
      }
      if (_disposed || _total != null) return;
      _total = lo;
      notifyListeners();
    } catch (_) {
      // Keep the speculative count; paging still works.
    } finally {
      _probing = false;
    }
  }

  @override
  void dispose() {
    _disposed = true;
    super.dispose();
  }
}

PagedList<T> _pagedList<T>(
  Ref ref,
  PageFetcher<T> fetch, {
  ListCount? count,
}) {
  ref.cacheFor(const Duration(minutes: 5));
  ref.invalidateOnCatalogChange();
  final list = PagedList<T>(fetch: fetch, count: count);
  ref.onDispose(list.dispose);
  return list;
}

Future<int> _count(Future<BigInt> Function() call) async =>
    (await call()).toInt();


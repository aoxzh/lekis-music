enum LibrarySegment { albums, artists, songs, genres }

/// A plain settable value. Write with `ref.read(p.notifier).set(v)`.
class SimpleValue<T> extends Notifier<T> {
  SimpleValue(this._initial);
  final T _initial;
  @override
  T build() => _initial;
  void set(T value) => state = value;
}

typedef SimpleValueProvider<T> = NotifierProvider<SimpleValue<T>, T>;

SimpleValueProvider<T> _valueProvider<T>(T initial) =>
    NotifierProvider<SimpleValue<T>, T>(() => SimpleValue<T>(initial));


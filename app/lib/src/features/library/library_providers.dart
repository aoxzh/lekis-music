/// Thumbnail widths we ask the core for. The core owns the cache; we only pick
/// the smallest bucket that is at least as large as the on-screen pixels.
const List<int> artworkWidthBuckets = [128, 256, 512, 1024];

/// The largest bucket – always generated by the core (ENR-12).
const int artworkFallbackWidth = 1024;

int artworkBucketFor(double physicalPx) {
  for (final b in artworkWidthBuckets) {
    if (b >= physicalPx) return b;
  }
  return artworkFallbackWidth;
}


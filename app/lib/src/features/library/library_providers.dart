extension LekisRefX on Ref {
  /// Keeps an auto-dispose provider alive for [duration] after its last
  /// listener goes away (cheap scroll-back without refetching).
  void cacheFor(Duration duration) {
    final link = keepAlive();
    Timer? timer;
    onCancel(() => timer = Timer(duration, link.close));
    onResume(() => timer?.cancel());
    onDispose(() => timer?.cancel());
  }

  /// Rebuilds the provider whenever the core reports a catalog change
  /// (scan finished, metadata edited, ...).
  void invalidateOnCatalogChange() {
    listen<AsyncValue<CoreEventDto>>(coreEventsProvider, (_, next) {
      final event = next.value;
      if (event is CoreEventDto_LibraryChanged &&
          event.scope == LibraryScopeDto.catalog) {
        invalidateSelf();
      }
    });
  }
}


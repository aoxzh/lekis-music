typedef PageFetcher<T> = Future<List<T>> Function(int offset, int limit);
typedef ListCount = Future<int> Function();

/// A sparse, page-cached view over a very long list (100k+ rows).
///
/// * Pages are fetched on demand when [itemAt] hits an unloaded page.
/// * Only [maxCachedPages] pages are kept (LRU), so memory stays flat.
/// * The total count comes from an exact `count*` bridge call when available;
///   otherwise it is discovered lazily (see [_probeTotal]).
class PagedList<T> extends ChangeNotifier {
  PagedList({
    required this._fetch,
    this.pageSize = 200,
    this.maxCachedPages = 40,
    this.count,
  }) {
    _load(0);
  }

  final PageFetcher<T> _fetch;

  /// Exact total row count, when the bridge can provide one.
  final ListCount? count;
  final int pageSize;
  final int maxCachedPages;

  /// How close to a page edge an item must be before the adjacent page is
  /// prefetched.
  static const int _prefetchThreshold = 24;

  // ignore: prefer_collection_literals — LinkedHashMap keeps LRU order.
  final LinkedHashMap<int, List<T>> _pages = LinkedHashMap<int, List<T>>();
  final Set<int> _inFlight = <int>{};
  int? _total;
  int _knownEnd = 0;
  int _generation = 0;
  Timer? _refreshDebounce;
  bool _firstPageLoaded = false;
  bool _probing = false;
  bool _disposed = false;
  Object? _error;

  Object? get error => _error;
  bool get isInitialLoading => !_firstPageLoaded && _error == null;
  bool get isEmpty => _total == 0;

  /// Exact once known; until then a speculative count that grows by one page
  /// beyond what we know exists, so scrolling keeps pulling pages in.
  int get itemCount => _total ?? (_knownEnd + pageSize);

  /// Returns the item, or `null` while its page is loading.
  T? itemAt(int index) {
    if (index < 0) return null;
    final total = _total;
    if (total != null && index >= total) return null;
    final page = index ~/ pageSize;
    final rows = _pages.remove(page);
    if (rows == null) {
      _load(page);
      return null;
    }
    _pages[page] = rows; // touch (LRU)
    final i = index - page * pageSize;
    final value = i < rows.length ? rows[i] : null;
    // Prefetch the neighbouring page while the user is still inside this one,
    // so scrolling across a page boundary does not flash placeholders.
    if (i >= rows.length - _prefetchThreshold) _prefetch(page + 1);
    if (i < _prefetchThreshold) _prefetch(page - 1);
    return value;
  }

  /// Starts a background page load unless it is already cached, in flight,
  /// or entirely past the known end of the list.
  void _prefetch(int page) {
    if (page < 0 || _pages.containsKey(page) || _inFlight.contains(page)) {
      return;
    }
    final total = _total;
    if (total != null && page * pageSize >= total) return;
    _load(page);
  }

  /// Loaded, contiguous items around [index] (for building a play queue
  /// without sending 100k ids). Returns the ids window and the start offset.
  (List<T> items, int start) loadedWindow(int index) {
    final page = index ~/ pageSize;
    final out = <T>[];
    var start = 0;
    for (var p = page - 1; p <= page + 1; p++) {
      final rows = _pages[p];
      if (rows == null) {
        if (p < page) continue;
        break;
      }
      if (p == page) start = out.length + (index - page * pageSize);
      out.addAll(rows);
    }
    return (out, start);
  }

  void retry() {
    _error = null;
    notifyListeners();
    _load(0);
  }

  /// 就地静默刷新已缓存的页与总数（合并短时间内的频繁事件），**不**重置滚动位置、
  /// **不**回退到骨架屏、也**不**在拉取完成前缩减 `itemCount`。
  ///
  /// 用于批量补全封面/标签等会高频触发 `LibraryChanged(Catalog)` 的场景。
  void refresh({Duration debounce = const Duration(milliseconds: 250)}) {
    if (_disposed) return;
    _refreshDebounce?.cancel();
    if (debounce <= Duration.zero) {
      refreshNow();
      return;
    }
    _refreshDebounce = Timer(debounce, refreshNow);
  }

  /// 立即执行一次就地刷新：优先重拉最近访问（当前视口附近）的已缓存页，并更新总数。
  void refreshNow() {
    if (_disposed) return;
    _refreshDebounce?.cancel();
    _refreshDebounce = null;
    _generation++;
    final gen = _generation;
    _inFlight.clear();
    _probing = false;
    final cachedPages = _pages.keys.toList(growable: false);
    if (cachedPages.isEmpty) {
      _load(0);
      return;
    }
    // 倒序遍历 LinkedHashMap：最近访问过的页（当前屏幕附近）排在最后，优先刷新。
    for (final page in cachedPages.reversed) {
      _load(page, generation: gen, replace: true);
    }
    if (count != null) {
      unawaited(_refreshTotal(gen));
    }
  }

  Future<void> _refreshTotal(int gen) async {
    final counter = count;
    if (counter == null) return;
    try {
      final total = await counter();
      if (_disposed || gen != _generation) return;
      _total = total;
      _pages.removeWhere((page, _) => page * pageSize >= total && page > 0);
      notifyListeners();
    } catch (_) {}
  }

  void _load(int page, {int? generation, bool replace = false}) {
    final gen = generation ?? _generation;
    if (_disposed || (!replace && _inFlight.contains(page))) return;
    _inFlight.add(page);
    _fetch(page * pageSize, pageSize).then(
      (rows) {
        if (gen == _generation) _inFlight.remove(page);
        if (_disposed || gen != _generation) return;
        _pages[page] = rows;
        if (page == 0) _firstPageLoaded = true;
        if (rows.length < pageSize) {
          final exactEnd = page * pageSize + rows.length;
          _total = exactEnd;
          _pages.removeWhere((p, _) => p > page);
        } else {
          _knownEnd = math.max(_knownEnd, (page + 1) * pageSize);
          if (page == 0 && !replace) unawaited(_probeTotal());
        }
        while (_pages.length > maxCachedPages) {
          _pages.remove(_pages.keys.first);
        }
        notifyListeners();
      },
      onError: (Object e) {
        if (gen == _generation) _inFlight.remove(page);
        if (_disposed || gen != _generation) return;
        if (page == 0 && !replace) _error = e;
        notifyListeners();
      },
    );
  }

  /// Gets the exact row count so the scrollbar is accurate and the user can
  /// fling straight to the end. Prefers the bridge's `count*` call; the
  /// single-row binary search is only a fallback for lists without one.
  Future<void> _probeTotal() async {
    if (_probing) return;
    _probing = true;
    try {
      if (count != null) {
        final total = await count!();
        if (_disposed || _total != null) return;
        _total = total;
        notifyListeners();
        return;
      }
      Future<bool> exists(int i) async => (await _fetch(i, 1)).isNotEmpty;
      var lo = pageSize; // count >= lo
      var hi = pageSize * 2;
      while (await exists(hi - 1)) {
        if (_disposed || _total != null) return;
        lo = hi;
        hi *= 2;
      }
      while (hi - lo > 1) {
        if (_disposed || _total != null) return;
        final mid = (lo + hi) ~/ 2;
        if (await exists(mid - 1)) {
          lo = mid;
        } else {
          hi = mid;
        }
      }
      if (_disposed || _total != null) return;
      _total = lo;
      notifyListeners();
    } catch (_) {
      // Keep the speculative count; paging still works.
    } finally {
      _probing = false;
    }
  }

  @override
  void dispose() {
    _disposed = true;
    _refreshDebounce?.cancel();
    _refreshDebounce = null;
    super.dispose();
  }
}

PagedList<T> _pagedList<T>(
  Ref ref,
  PageFetcher<T> fetch, {
  ListCount? count,
  bool refreshOnUserState = false,
}) {
  ref.cacheFor(const Duration(minutes: 5));
  final list = PagedList<T>(fetch: fetch, count: count);
  // 资料库变更（如后台逐首补全封面）时就地刷新页缓存，保持 PagedList 实例与滚动位置不变。
  ref.listen<AsyncValue<CoreEventDto>>(coreEventsProvider, (_, next) {
    final event = next.value;
    if (event is CoreEventDto_LibraryChanged &&
        (event.scope == LibraryScopeDto.catalog ||
            (refreshOnUserState && event.scope == LibraryScopeDto.userState))) {
      list.refresh();
    }
  });
  ref.onDispose(list.dispose);
  return list;
}

